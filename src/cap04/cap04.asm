// Difficulty: Beginner
// =============================================
:BasicUpstart2(start)

start:
    // Pulisci schermo
    jsr clearScreen

    // Imposta puntatore sprite 0 a blocco 13 ($0340 / 64 = 13)
    lda #13
    sta $07F8

    // Colore sprite 0 = giallo (7)
    lda #7
    sta $D027

    // Posizione centrale: X=170, Y=140
    lda #170
    sta $D000
    lda #140
    sta $D001

    // Attiva sprite 0
    lda #%00000001
    sta $D015

    // Ciclo infinito
!loop:
    jmp !loop-

// ----------------------------------
// clearScreen — Pulisce Screen RAM
// ----------------------------------
clearScreen:
    lda #32           // Spazio
    ldx #0
!loop:
    sta $0400, x
    sta $0500, x
    sta $0600, x
    sta $0700, x
    inx
    bne !loop-
    rts

